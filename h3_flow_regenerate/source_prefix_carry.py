"""Experimental, hash-paired native source context for sequential H3 chunks."""

from __future__ import annotations

import hashlib
import math
import threading
import time
from contextlib import contextmanager
from dataclasses import dataclass
from functools import wraps

import torch
import torch.nn.functional as F

from .decode_context import _frames, video_latent_fingerprint

SOURCE_PREFIX_CARRY_KEY = "h3_flow_source_prefix_carry_v1"
SOURCE_PREFIX_CARRY_POLICY = "native_source_carry_v1"
SOURCE_PREFIX_TARGET_BAND_POLICY = "native_source_carry_target_band_v1"
# Latent-space constants for target-band reconciliation, in source latent cells
# (16 source pixels each). The band is a mirror-padded Gaussian low-pass with
# amplitude response 0.92 at a 16-cell wavelength, 0.73 at 8 and 0.29 at 4 cells.
# It passes a spatially constant difference to float32 precision; near borders it does not
# conserve the spatial mean of a varying difference.
TARGET_BAND_SIGMA = 1.0
# Structure agreement is judged on a mid band, gaussian(1) - gaussian(4), so a
# uniform or very slow latent offset never counts as disagreement. The ratio
# r = |mid(G) - mid(C)| / rms(mid(C), mid(G)) is pooled over channels and
# smoothed locally. For equal-amplitude content displaced by a fraction p of its
# wavelength, ideally r = 2|sin(pi p)| (an approximation: the floor and local
# pooling modify it); uncorrelated content gives r ~ 1.41. Carry detail
# is replaced by the target's from r = 0.35 (p ~ 0.06) and fully from r = 0.7
# (p ~ 0.11). The gate sees only mid-band structure: content that differs only
# above the band keeps the carry's component. The target's fine texture is
# regenerated by target-high and is generally uncorrelated with the carry's, so a
# fine-band detector would replace carry detail nearly everywhere and reduce the
# prefix to the latent resize this option exists to avoid.
TARGET_BAND_GATE_SIGMA = 4.0
TARGET_BAND_GATE = (0.35, 0.7)


def _owned_video(video):
    if (
        not torch.is_tensor(video)
        or video.ndim != 5
        or tuple(video.shape[:2]) != (1, 24)
        or not video.is_floating_point()
        or any(n % 2 for n in video.shape[-2:])
        or not bool(torch.isfinite(video).all())
    ):
        raise ValueError("native source carry requires finite [1,24,T,H,W] video on an even grid")
    _frames(int(video.shape[2]))
    return video.detach().to(device="cpu", dtype=torch.float32, copy=True).contiguous()


@dataclass(frozen=True)
class _Snapshot:
    source: torch.Tensor
    target_hw: tuple[int, int]
    target_suffix_hashes: dict[int, str]
    generation: int
    sequence: tuple[str | None, int] | None
    initial: bool


class SourcePrefixCarry:
    """One CPU source clip, paired with suffix hashes of its returned target.

    A complete outer sampling transaction publishes the next pair. Nested
    Flow wrappers of that same guider share the transaction; another guider
    cannot enter it. No generated state is retained on CUDA.
    """

    def __init__(self, *, target_band=False):
        self.target_band = bool(target_band)
        self._lock = threading.Lock()
        self._thread = None
        self._guider = None
        self._snapshot = None
        self._source = None
        self._pending = None
        self._generation = 0
        self._initial = False

    @contextmanager
    def transaction(self, guider):
        thread = threading.get_ident()
        if self._thread == thread and self._guider is guider:
            yield
            return
        if not self._lock.acquire(blocking=False):
            raise RuntimeError("native source carry is already sampling another chunk")
        self._thread, self._guider = thread, guider
        self._source = self._pending = None
        self._initial = False
        try:
            yield
            if self._pending is not None:
                self._snapshot = self._pending
                self._generation = self._pending.generation
        finally:
            self._source = self._pending = None
            self._initial = False
            self._thread = self._guider = None
            self._lock.release()

    def _require_transaction(self):
        if self._thread != threading.get_ident():
            raise RuntimeError("native source carry requires an active sampling transaction")

    def _sequence(self):
        options = getattr(self._guider, "model_options", None) or {}
        request = (options.get("transformer_options") or {}).get("h3_continuum")
        if not isinstance(request, dict) or request.get("active") is not True:
            return None
        try:
            chunk = int(request["chunk_index"])
        except (KeyError, ValueError, TypeError):
            raise ValueError("native source carry requires an integer Continuum chunk index") from None
        session = request.get("session_id")
        return (str(session) if session is not None else None), chunk

    def begin_initial(self):
        self._require_transaction()
        self._snapshot = None
        self._initial = True

    def stage_source(self, video):
        self._require_transaction()
        if self._source is not None:
            raise RuntimeError("native source carry already staged a clean prediction for this chunk")
        self._source = _owned_video(video)

    def prepare_success(self, target):
        self._require_transaction()
        started = time.perf_counter()
        source = self._source
        if source is None:
            raise RuntimeError("native source carry lost this chunk's low/probe clean prediction")
        target = _owned_video(target)
        if source.shape[2] != target.shape[2] or any(
            a >= b for a, b in zip(source.shape[-2:], target.shape[-2:], strict=True)
        ):
            raise ValueError("native source carry requires paired temporal lengths and a larger target grid")
        hashes = {
            n: hashlib.sha256(target[:, :, -n:].contiguous().numpy().tobytes()).hexdigest()
            for n in range(2, target.shape[2] + 1, 5)
        }
        self._pending = _Snapshot(
            source, tuple(target.shape[-2:]), hashes, self._generation + 1, self._sequence(), self._initial
        )
        return {
            "policy": SOURCE_PREFIX_CARRY_POLICY,
            "generation": self._pending.generation,
            "source_shape": list(source.shape),
            "target_shape": list(target.shape),
            "retained_cpu_bytes": source.numel() * source.element_size(),
            "retained_cuda_bytes": 0,
            "source_role": "low_probe_clean_prediction_at_handoff_sigma",
            "sequence": self._pending.sequence,
            "initial_chunk": self._pending.initial,
            "explicit_session_id_present": self._pending.sequence is not None and self._pending.sequence[0] is not None,
            "publication": "after_successful_outer_sampling_transaction",
            "elapsed_ms": (time.perf_counter() - started) * 1000,
            "extra_h3_nfe": 0,
            "extra_vae_calls": 0,
        }

    def project(self, prefix, source_h, source_w):
        self._require_transaction()
        started = time.perf_counter()
        exact = _owned_video(prefix)
        snapshot = self._snapshot
        if snapshot is None:
            raise RuntimeError("native_source_carry requires a preceding successful chunk from this patched MODEL")
        n = int(exact.shape[2])
        fingerprint = video_latent_fingerprint(exact)
        sequence = self._sequence()
        # Continuum labels continuation chunks only: its initial Flow pass is
        # standalone, then the first labeled request is chunk 2. Bind that one
        # transition by the exact target hash below, never a previous unlabeled
        # continuation. Later requests must advance the labeled session.
        initial_transition = (
            snapshot.initial and snapshot.sequence is None and sequence is not None and sequence[1] == 2
        )
        if (
            not initial_transition
            and (sequence is not None or snapshot.sequence is not None)
            and (
                sequence is None
                or snapshot.sequence is None
                or sequence[0] != snapshot.sequence[0]
                or sequence[1] != snapshot.sequence[1] + 1
            )
        ):
            raise RuntimeError("native_source_carry requires the immediately preceding chunk in the same sequence")
        if (
            tuple(exact.shape[-2:]) != snapshot.target_hw
            or tuple(snapshot.source.shape[-2:]) != (source_h, source_w)
            or snapshot.target_suffix_hashes.get(n) != fingerprint["sha256_float32"]
        ):
            raise RuntimeError(
                "native_source_carry prefix does not match the preceding returned target suffix, grid or temporal phase"
            )
        projected = snapshot.source[:, :, -n:].clone()
        return projected, {
            "policy": SOURCE_PREFIX_CARRY_POLICY,
            "mode": "native_source_carry",
            "generation": snapshot.generation,
            "previous_sequence": snapshot.sequence,
            "current_sequence": sequence,
            "initial_unlabeled_to_chunk_2": initial_transition,
            "explicit_session_id_verified": (
                snapshot.sequence is not None
                and sequence is not None
                and snapshot.sequence[0] is not None
                and sequence[0] is not None
            ),
            "prefix_t": n,
            "authoritative_prefix": fingerprint,
            "authoritative_prefix_preserved_bitwise": True,
            "projected_prefix": video_latent_fingerprint(projected),
            "previous_source_token_span": [int(snapshot.source.shape[2]) - n, int(snapshot.source.shape[2])],
            "native_temporal_phase_verified": True,
            "source_role": "previous_chunk_low_probe_clean_prediction_at_handoff_sigma",
            "scope": "protected_prefix_only_before_low_sampling",
            "extra_h3_nfe": 0,
            "extra_vae_decode_calls": 0,
            "extra_vae_encode_calls": 0,
            "elapsed_ms": (time.perf_counter() - started) * 1000,
        }


def _gaussian_blur(video, sigma):
    radius = max(1, math.ceil(3.0 * sigma))
    offsets = torch.arange(-radius, radius + 1, dtype=torch.float32, device=video.device)
    kernel = torch.exp(-0.5 * (offsets / sigma).square())
    kernel = kernel / kernel.sum()
    b, c, t, h, w = video.shape
    work = video.permute(0, 2, 1, 3, 4).reshape(b * t * c, 1, h, w)
    # Mirror padding keeps fine alternating detail alternating at the border;
    # edge replication would turn it into spurious low-frequency structure.
    mode_w = "reflect" if radius < w else "replicate"
    mode_h = "reflect" if radius < h else "replicate"
    work = F.conv2d(F.pad(work, (radius, radius, 0, 0), mode=mode_w), kernel.view(1, 1, 1, -1))
    work = F.conv2d(F.pad(work, (0, 0, radius, radius), mode=mode_h), kernel.view(1, 1, -1, 1))
    return work.reshape(b, t, c, h, w).permute(0, 2, 1, 3, 4)


def _rms(value):
    return float(value.square().mean().sqrt().item())


def reconcile_target_band(carry, target_projection, *, sigma=TARGET_BAND_SIGMA, gate=TARGET_BAND_GATE):
    """Take the carried prefix's low spatial band from the returned target.

    ``carry`` (C) is the preceding low/probe clean prediction; ``target_projection``
    (G) is the authoritative target prefix resized to the same source grid. With
    ``D = G - C`` and ``B = gaussian_sigma(D)``, each frame and channel becomes
    ``C + B + w * (D - B)``. The weight ``w`` rises from 0 to 1 with the local
    disagreement of mid-band structure, ``g_1 - g_4``, between C and G. These are
    latent-space properties:

    - the band ``g_1(D)`` is taken from the target, and a spatially constant
      difference transfers to float32 precision (the spatial mean of a varying
      difference is not conserved near borders);
    - where ``w = 0``, the carry's above-band component is kept, including when
      C and G differ only above the band;
    - where ``w = 1``, the output equals G algebraically, i.e. to float32
      arithmetic precision rather than bitwise.

    Whether this preserves decoded objects, geometry or tone is a hypothesis for
    rendered validation, not a property of this function.
    """
    started = time.perf_counter()
    if (
        not torch.is_tensor(carry)
        or not torch.is_tensor(target_projection)
        or carry.ndim != 5
        or carry.shape != target_projection.shape
    ):
        raise ValueError("target-band carry reconciliation requires paired source-grid prefixes")
    sigma = float(sigma)
    low, high = (float(v) for v in gate)
    if not math.isfinite(sigma) or sigma <= 0.0:
        raise ValueError("target-band carry reconciliation requires a positive sigma")
    if not (math.isfinite(low) and math.isfinite(high) and 0.0 <= low < high):
        raise ValueError("target-band carry reconciliation requires an increasing gate")
    work_carry = carry.detach().to(dtype=torch.float32)
    work_target = target_projection.detach().to(device=work_carry.device, dtype=torch.float32)
    difference = work_target - work_carry
    if not bool(torch.isfinite(difference).all()):
        raise ValueError("target-band carry reconciliation requires finite prefixes")
    band = _gaussian_blur(difference, sigma)
    above = difference - band

    def mid(video):
        return _gaussian_blur(video, sigma) - _gaussian_blur(video, TARGET_BAND_GATE_SIGMA)

    carry_mid, target_mid = mid(work_carry), mid(work_target)
    disagreement = _gaussian_blur((target_mid - carry_mid).square().sum(1, keepdim=True), sigma)
    content = _gaussian_blur((carry_mid.square() + target_mid.square()).sum(1, keepdim=True), sigma) * 0.5
    floor = 0.05 * content.mean(dim=(-2, -1), keepdim=True) + 1e-12
    ratio = (disagreement / (content + floor)).sqrt()
    weight = ((ratio - low) / (high - low)).clamp(0.0, 1.0)
    replaced = weight * above
    reconciled = (work_carry + band + replaced).to(carry)
    if not bool(torch.isfinite(reconciled).all()):
        raise ValueError("target-band carry reconciliation produced a non-finite prefix")
    return reconciled, {
        "policy": SOURCE_PREFIX_TARGET_BAND_POLICY,
        "band": "gaussian_spatial_lowpass_mirror_padded",
        "sigma_source_cells": sigma,
        "detail_gate": "mid_band_structure_disagreement",
        "detail_gate_sigma_source_cells": [sigma, TARGET_BAND_GATE_SIGMA],
        "detail_gate_ratio": [low, high],
        "detail_gate_weight_mean": float(weight.mean().item()),
        "detail_gate_active_fraction": float((weight > 0.0).float().mean().item()),
        "detail_gate_full_fraction": float((weight >= 1.0).float().mean().item()),
        "carry_to_target_rms": _rms(difference),
        "carry_to_target_mean_rms": _rms(difference.mean(dim=(-2, -1))),
        "carry_to_target_band_rms": _rms(band),
        "carry_to_target_above_band_rms": _rms(above),
        "replaced_above_band_rms": _rms(replaced),
        "last_token_band_rms": _rms(band[:, :, -1:]),
        "temporal_mixing": False,
        "extra_h3_nfe": 0,
        "extra_vae_calls": 0,
        "elapsed_ms": (time.perf_counter() - started) * 1000,
    }


def source_carry_owner(guider):
    value = (getattr(guider, "model_options", None) or {}).get(SOURCE_PREFIX_CARRY_KEY)
    if value is not None and not isinstance(value, SourcePrefixCarry):
        raise TypeError("invalid native source carry owner")
    return value


def source_carry_scope(*, outer=False):
    def decorate(function):
        @wraps(function)
        def wrapped(*args, **kwargs):
            guider = (
                (args[0] if args else kwargs["executor"]).class_obj
                if outer
                else (args[1] if len(args) > 1 else kwargs["guider"])
            )
            owner = source_carry_owner(guider)
            if owner is None:
                return function(*args, **kwargs)
            with owner.transaction(guider):
                return function(*args, **kwargs)

        return wrapped

    return decorate
